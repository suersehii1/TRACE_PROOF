/* 실제 브라우저에서 결함 검증 → 보류 → 정상 재검증 → 승인 → 보고서를 확인한다. */
const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.BASE_URL || 'http://localhost:8088'
const root = path.resolve(__dirname, '..')
const output = path.join(root, 'docs', 'screenshots')
fs.mkdirSync(output, { recursive: true })

;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.UI_BROWSER ? { executablePath: process.env.UI_BROWSER } : { channel: 'chrome' }) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(base)
  await page.getByLabel('비교 데이터', { exact: true }).selectOption({ label: '결함 수정 버전 · v1.1.0' })
  await page.getByRole('button', { name: '검증 실행', exact: true }).click()
  await page.locator('.result-heading .status.fail').waitFor()
  assert.equal(await page.getByRole('button', { name: '검토 승인', exact: true }).isDisabled(), true)
  await page.locator('.evidence-button').first().click()
  await page.locator('dialog[open]').waitFor()
  assert.ok((await page.locator('dialog').innerText()).includes('기대 기준'))
  await page.getByRole('button', { name: '근거 창 닫기' }).click()
  await page.getByPlaceholder('이름 또는 담당자 ID').fill('시연 담당자')
  await page.getByPlaceholder('확인한 내용과 후속 조치를 기록하세요.').fill('결함 버전의 단위·시간·작업 연결 오류를 확인하여 보류합니다.')
  await page.getByRole('button', { name: '보류 기록', exact: true }).click()
  await page.locator('.review-card .status.hold').first().waitFor()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: path.join(output, 'desktop-validation.png'), fullPage: false })
  await page.getByLabel('비교 데이터', { exact: true }).selectOption({ label: '정상 수정 버전 · v1.1.1' })
  await page.getByRole('button', { name: '검증 실행', exact: true }).click()
  await page.locator('.result-heading .status.pass').waitFor()
  await page.getByPlaceholder('확인한 내용과 후속 조치를 기록하세요.').fill('정상 버전의 필수 검사와 원본을 확인했습니다.')
  await page.getByRole('button', { name: '검토 승인', exact: true }).click()
  await page.locator('.review-card .status.approved').first().waitFor()
  const popupEvent = page.waitForEvent('popup')
  await page.getByRole('link', { name: /보고서 열기/ }).click()
  const popup = await popupEvent
  await popup.waitForLoadState('domcontentloaded')
  assert.ok((await popup.locator('body').innerText()).includes('검토 승인'))
  await popup.screenshot({ path: path.join(output, 'report.png'), fullPage: true })
  await popup.close()

  // 휴대폰 화면 폭에서 주요 업무가 가능하고 페이지 전체가 가로로 넘치지 않아야 한다.
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  mobile.on('pageerror', e => errors.push(e.message))
  await mobile.goto(base)
  await mobile.getByLabel('비교 데이터', { exact: true }).selectOption({ label: '결함 수정 버전 · v1.1.0' })
  await mobile.getByRole('button', { name: '검증 실행', exact: true }).click()
  await mobile.locator('.result-heading .status.fail').waitFor()
  await mobile.getByRole('button', { name: '검증 실행', exact: true }).waitFor()
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await mobile.evaluate(() => window.scrollTo(0, 0))
  await mobile.screenshot({ path: path.join(output, 'mobile-validation.png'), fullPage: false })
  await mobile.getByRole('button', { name: '장비 데이터', exact: true }).click()
  await mobile.locator('.release-card').first().waitFor()
  await mobile.locator('input[type=file]').setInputFiles(path.join(root, 'RAW_DATA', 'healthy.json'))
  await mobile.getByRole('status').filter({ hasText: '이미 등록된 원본' }).waitFor()
  await mobile.getByRole('button', { name: '장비에서 전송', exact: true }).click()
  await mobile.getByRole('status').filter({ hasText: '동일한 원본' }).waitFor()
  assert.deepEqual(errors, [])
  await browser.close()
  console.log(JSON.stringify({ result: 'PASS', desktop: '1440x1050', mobile: '390x844', pageErrors: errors, screenshots: output }))
})().catch(e => { console.error(e); process.exit(1) })
